-- 0006_v2: the release an issue started in and the one it came back in,
-- custom events from PostHog SDKs and their hourly summaries, and an
-- index for one person's page views (the journey before an error and the
-- user activity page).

-- The release of the event that created the issue; '' when it had none.
ALTER TABLE issues ADD COLUMN first_release TEXT NOT NULL DEFAULT '';
-- The release of the event that last opened the issue again (see
-- regressed_at); '' when it never came back or that event had no release.
ALTER TABLE issues ADD COLUMN regressed_release TEXT NOT NULL DEFAULT '';

-- Issues from before this migration: the release of their oldest stored
-- event, and of the event that reopened them (it was received at
-- regressed_at).
UPDATE issues SET first_release = COALESCE((
    SELECT e.release FROM error_events e WHERE e.issue_id = issues.id
    ORDER BY e.timestamp, e.id LIMIT 1), '');
UPDATE issues SET regressed_release = COALESCE((
    SELECT e.release FROM error_events e WHERE e.issue_id = issues.id AND e.received_at = issues.regressed_at
    ORDER BY e.id LIMIT 1), '')
WHERE regressed_at IS NOT NULL;

-- One person's page views, newest first.
CREATE INDEX pageviews_project_user_start ON pageviews (project_id, user_id, start);

-- One row per PostHog event whose name does not start with "$" (the app's
-- own events, such as checkout_completed).
CREATE TABLE custom_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT  NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    -- The event's uuid, so an SDK that sends it again stores it once.
    event_id   TEXT    NOT NULL,
    name       TEXT    NOT NULL,
    -- distinct_id: anonymous until the app calls identify.
    user_id    TEXT    NOT NULL DEFAULT '',
    -- The page it happened on: its path (secrets masked) and route.
    path       TEXT    NOT NULL DEFAULT '',
    route      TEXT    NOT NULL DEFAULT '',
    at         BIGINT  NOT NULL,
    -- Bots are stored but counted apart.
    is_bot     BOOLEAN NOT NULL DEFAULT FALSE,
    -- The app's own properties (not the SDK's "$" ones), scrubbed, as JSON.
    properties TEXT    NOT NULL DEFAULT '{}',
    UNIQUE (project_id, event_id)
);

CREATE INDEX custom_events_project_at ON custom_events (project_id, at);
CREATE INDEX custom_events_project_user_at ON custom_events (project_id, user_id, at);

-- Per project, event name and clock hour (UTC): what the Events screen
-- shows. Rebuilt by the aggregation job from custom_events, for the hours
-- in stats_dirty_hours, together with hourly_stats.
CREATE TABLE event_hourly (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name       TEXT   NOT NULL,
    -- The hour's start, unix milliseconds.
    hour       BIGINT NOT NULL,
    -- Events sent by people (bots are only in bots).
    events     BIGINT NOT NULL DEFAULT 0,
    -- The people's user ids as a mergeable sketch (internal/hll).
    users_hll  BYTEA  NOT NULL,
    bots       BIGINT NOT NULL DEFAULT 0,
    UNIQUE (project_id, hour, name)
);
