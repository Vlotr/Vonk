-- 0007_sourcemaps: source maps uploaded through Sentry's upload API
-- (sentry-cli, @sentry/vite-plugin), and the API tokens those tools sign
-- in with.

-- One row per file of an uploaded artifact bundle: a source map or the
-- minified file it belongs to. The file itself lives on disk under
-- <DATA_DIR>/sourcemaps/ (path); retention counts from uploaded_at.
CREATE TABLE source_maps (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    -- The release the bundle was uploaded for; '' when it named none
    -- (uploads with debug ids need no release).
    release     TEXT   NOT NULL DEFAULT '',
    dist        TEXT   NOT NULL DEFAULT '',
    -- The file's URL as the bundle names it, such as ~/assets/index-D8xk2Lp1.js.map
    -- (~ stands for any scheme and host).
    file        TEXT   NOT NULL,
    -- source_map or minified_source.
    kind        TEXT   NOT NULL,
    -- The debug id that ties a minified file to its source map; '' without one.
    debug_id    TEXT   NOT NULL DEFAULT '',
    -- For a minified file: the source map it points to (its Sourcemap
    -- header or sourceMappingURL), relative to file; '' when it names none.
    sourcemap   TEXT   NOT NULL DEFAULT '',
    -- The SHA-1 of the bundle it came in, so the same bundle uploaded again
    -- is stored once.
    bundle      TEXT   NOT NULL,
    -- Relative to <DATA_DIR>/sourcemaps/.
    path        TEXT   NOT NULL,
    size        BIGINT NOT NULL,
    uploaded_at BIGINT NOT NULL
);

CREATE INDEX source_maps_project_debug_id ON source_maps (project_id, debug_id);
CREATE INDEX source_maps_project_release_file ON source_maps (project_id, release, file);
CREATE INDEX source_maps_project_bundle ON source_maps (project_id, bundle);
CREATE INDEX source_maps_project_uploaded ON source_maps (project_id, uploaded_at);

-- Tokens for the upload API (Authorization: Bearer <token>), made by
-- admins in Settings and shown once. Like session tokens, only an HMAC of
-- the token keyed with SECRET_KEY is stored.
CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT   NOT NULL,
    token_hash   TEXT   NOT NULL UNIQUE,
    -- The token's last four characters, so admins can tell tokens apart.
    hint         TEXT   NOT NULL DEFAULT '',
    created_by   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at   BIGINT NOT NULL,
    -- When an upload last signed in with it; NULL when never.
    last_used_at BIGINT
);

-- The projects a token may upload to.
CREATE TABLE api_token_projects (
    token_id   BIGINT NOT NULL REFERENCES api_tokens (id) ON DELETE CASCADE,
    project_id BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    PRIMARY KEY (token_id, project_id)
);

CREATE INDEX api_token_projects_project ON api_token_projects (project_id);
